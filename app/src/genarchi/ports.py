"""Ports : les seules interfaces que le code métier connaît (contrat d'exécution, A4)."""

from __future__ import annotations

from datetime import datetime
from typing import Protocol

from .domain import Event, EventStats, Order, Ticket


class Store(Protocol):
    def ping(self) -> None: ...
    def create_event(self, event: Event) -> Event: ...
    def get_event(self, event_id: str) -> Event | None: ...
    def list_events(self) -> list[Event]: ...
    def place_order(
        self, event_id: str, idempotency_key: str, buyer_email: str, quantity: int, request_hash: str
    ) -> tuple[Order, bool]:
        """Décrémente le stock et crée commande + billets atomiquement (I1).

        Retourne (commande, créée). Rejouer la même clé renvoie la commande existante (I2) ;
        lève Problem(409, idempotency_conflict) si la clé a servi avec un autre corps.
        """
        ...

    def get_order(self, order_id: str) -> Order | None: ...
    def get_ticket(self, ticket_id: str) -> Ticket | None: ...
    def list_pending(self, older_than: datetime, limit: int) -> list[Ticket]: ...
    def mark_issued(self, ticket_id: str, qr_object: str, at: datetime) -> tuple[Ticket, bool]:
        """Passe le billet `issued` s'il est `pending`. Retourne (billet, changé)."""
        ...

    def mark_scanned(self, ticket_id: str, at: datetime) -> tuple[Ticket, bool]: ...
    def stats(self, event_id: str) -> EventStats | None: ...
    def close(self) -> None: ...


class BlobStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes | None: ...
    def signed_url(self, key: str, ttl_seconds: int) -> str | None: ...


class Publisher(Protocol):
    def publish(self, event: dict) -> None: ...
    def close(self) -> None: ...
